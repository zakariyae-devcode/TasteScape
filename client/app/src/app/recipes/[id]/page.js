export function generateStaticParams() {
  return recipesCatalog.map((recipe) => ({
    id: recipe.id,
  }));
}

async function RecipeDetailLoader({ paramsPromise }) {
  const { id } = await paramsPromise;
  const recipe = recipesCatalog.find((item) => item.id === id) || null;
  return <RecipeDetailView recipe={recipe} />;
}

export default function RecipeDetailPage({ params }) {
  return (
    <Suspense
      fallback={
        <div
          dir="rtl"
          className="flex min-h-[50vh] items-center justify-center bg-[#faf4ea] px-4 py-16 text-sm font-extrabold text-stone-700 dark:bg-[#17110c] dark:text-amber-200"
        >
          جاري تحميل تفاصيل الوصفة...
        </div>
      }
    >
      <RecipeDetailLoader paramsPromise={params} />
    </Suspense>
  );
}