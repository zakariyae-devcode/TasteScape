import PDFDocument from "pdfkit";
import Recipe from "../models/Recipe.js";

export const generateRecipePdfService = async (recipeId, res) => {
    // 1. جلب الوصفة من قاعدة البيانات
    const recipe = await Recipe.findById(recipeId).populate("author", "username");
    if (!recipe) {
        throw new Error("RECIPE_NOT_FOUND");
    }

    // 2. إنشاء مستند PDF جديد
    const doc = new PDFDocument({ margin: 50, size: 'A4' });

    // 3. إعداد هيدر الاستجابة (Headers)
    res.setHeader("Content-Type", "application/pdf");
    res.setHeader("Content-Disposition", `attachment; filename=${recipe.title.replace(/\s+/g, '_')}.pdf`);

    doc.pipe(res);

    // 4. تصميم محتوى الـ PDF
    // عنوان الوصفة
    doc.fontSize(24).fillColor("#2c3e50").text(recipe.title, { align: 'center' });
    doc.moveDown();

    // الوصف المختصر (تم تصحيح الخطأ هنا)
    doc.fontSize(12).fillColor("#7f8c8d").text(recipe.description, { align: 'center' });
    doc.moveDown(2);

    // معلومات عامة
    doc.fontSize(10).fillColor("#34495e");
    doc.text(`Category: ${recipe.category} | Prep Time: ${recipe.prepTime} mins | Cook Time: ${recipe.cookTime} mins | Servings: ${recipe.servings}`);
    doc.moveDown(1.5);

    // خط فاصل
    doc.moveTo(50, doc.y).lineTo(545, doc.y).stroke("#bdc3c7");
    doc.moveDown(1.5);

    // قسم المكونات
    doc.fontSize(16).fillColor("#e67e22").text("Ingredients:");
    doc.moveDown(0.5);
    
    recipe.ingredients.forEach((ingredient) => {
        // تم تصحيح الخطأ هنا أيضاً
        doc.fontSize(11).fillColor("#2c3e50").text(`• ${ingredient}`);
    });
    doc.moveDown(1.5);

    // قسم خطوات التحضير
    doc.fontSize(16).fillColor("#e67e22").text("Instructions:");
    doc.moveDown(0.5);

    recipe.instructions.forEach((instruction, index) => {
        doc.fontSize(11).fillColor("#2c3e50").text(`${index + 1}. ${instruction}`, { align: 'left' });
        doc.moveDown(0.5);
    });

    // تذييل الصفحة
    doc.fontSize(8).fillColor("#95a5a6").text("Generated by TasteScape App 🍲", 50, 750, { align: 'center' });

    doc.end();
};